inline const Glyph* getGlyph(char c, bool trueCase = false) {
  if (c >= '0' && c <= '9') return &digitGlyphs[c - '0'];
  if (c >= 'A' && c <= 'Z') return &letterGlyphs[c - 'A'];
  if (c >= 'a' && c <= 'z') {
    if (trueCase) {
      return &lowercaseGlyphs[c - 'a'];
    } else {
      return &letterGlyphs[c - 'a'];
    }
  }
  if (c >= 32 && c <= 126) return &asciiGlyphs[c - 32];
  return nullptr;
}

template<typename DisplayType>
void drawString(DisplayType& display, int16_t x, int16_t y, const char* str, uint16_t color, bool trueCase = false) {
  int16_t cursorX = x;
  while (*str) {
    const Glyph* g = getGlyph(*str, trueCase);
    if (g) {
      display.drawBitmap(cursorX, y, g->bitmap, g->w, FONT_H, color);
      cursorX += g->w + 1;  // 1px spacing between glyphs
    } else {
      cursorX += 3;  // fallback spacing for unsupported chars
    }
    str++;
  }
}

inline uint16_t stringWidth(const char* str, bool trueCase = false) {
  uint16_t width = 0;
  while (*str) {
    const Glyph* g = getGlyph(*str, trueCase);
    if (g) {
      width += g->w + 1;  // 1px spacing between glyphs
    } else {
      width += 3;  // fallback spacing for unsupported chars
    }
    str++;
  }
  if (width > 0) width--;  // remove trailing spacing
  return width;
}
